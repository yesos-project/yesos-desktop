#!/usr/bin/env python3
"""
Generates src/audio_tables.c. The kernel stays integer-only: every table is
computed here, on the host, and committed.

  g_sine_q15[1024]      one sine period, Q15 (32767 = 1.0), read without
                        interpolation by `audio tone`
  g_sine_q31[1025]      one sine period, Q31, plus a guard point so that
                        linear interpolation never wraps (`audio play`)
  g_eml_sinc_q15[65][8] the EML polyphase bank from yesos-lab: an 8-tap sinc
                        with a Blackman window of half-width 4, at 64 + 1
                        fractional positions; each row sums to 32768

Usage: python3 tools/gen_audio_tables.py > src/audio_tables.c
"""
import math

N = 1024
TAPS, PHASES = 8, 64


def sinc(x):
    return 1.0 if x == 0 else math.sin(math.pi * x) / (math.pi * x)


def sinc_row(tau):
    # taps sit at k - 3 - tau for k = 0..7 (the output lies between taps 3 and 4)
    h = []
    for k in range(TAPS):
        x = k - 3 - tau
        w = 0.42 + 0.5 * math.cos(math.pi * x / 4) + 0.08 * math.cos(2 * math.pi * x / 4)
        h.append(sinc(x) * w)
    s = sum(h)
    q = [round(v / s * 32768) for v in h]
    q[q.index(max(q))] += 32768 - sum(q)          # exact unity gain at DC
    return q


def emit(decl, vals, per_line, width):
    print(f"{decl} = {{")
    for i in range(0, len(vals), per_line):
        print("    " + ", ".join(f"{v:{width}d}" for v in vals[i:i + per_line]) + ",")
    print("};")
    print()


print("// Generated by tools/gen_audio_tables.py: do not edit.")
print('#include "types.h"')
print()
emit(f"const I16 g_sine_q15[{N}]", [round(32767 * math.sin(2 * math.pi * i / N)) for i in range(N)], 12, 6)
emit(f"const I32 g_sine_q31[{N + 1}]",
     [round(2147483647 * math.sin(2 * math.pi * i / N)) for i in range(N + 1)], 6, 11)
print(f"const I32 g_eml_sinc_q15[{PHASES + 1}][{TAPS}] = {{")
for p in range(PHASES + 1):
    print("    { " + ", ".join(f"{v:6d}" for v in sinc_row(p / PHASES)) + f" }},   // tau = {p}/{PHASES}")
print("};")
