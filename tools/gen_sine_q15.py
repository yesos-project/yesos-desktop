#!/usr/bin/env python3
"""
Generates src/sine_q15.c: one period of a sine, 1024 points, as Q15 integers
(round(32767 * sin(2*pi*i/1024))). The kernel stays integer-only: the table is
computed here, on the host, and committed.

Usage: python3 tools/gen_sine_q15.py > src/sine_q15.c
"""
import math

N = 1024
vals = [round(32767 * math.sin(2 * math.pi * i / N)) for i in range(N)]
print("// Generated by tools/gen_sine_q15.py: do not edit.")
print("// One sine period, 1024 points, Q15 (32767 = 1.0).")
print('#include "types.h"')
print()
print(f"const I16 g_sine_q15[{N}] = {{")
for i in range(0, N, 12):
    print("    " + ", ".join(f"{v:6d}" for v in vals[i:i + 12]) + ",")
print("};")
